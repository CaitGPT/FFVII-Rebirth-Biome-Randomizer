"""Generate a hash-bound runtime compatibility manifest; never embeds an asset.

The manifest contains offsets, names and a structural fingerprint only. The
runtime must validate all of them before permitting a scoped FName write.
"""
from pathlib import Path
import argparse, hashlib, json, struct

ORIGINAL_SHA256='53b677c942bce605fde70f754e84491daf117f1c47dfd4b32457c63c180b95b8'

def layout(path):
    data=path.read_bytes()
    if hashlib.sha256(data).hexdigest()!=ORIGINAL_SHA256:
        raise ValueError('Unreviewed original territory asset')
    u32=lambda p:struct.unpack_from('<I',data,p)[0]
    names=[];p=u32(0x18);end=p+u32(0x1c)
    while p<end:
        wide=data[p]&0x80;length=((data[p]&0x7f)<<8)|data[p+1];p+=2
        count=length*(2 if wide else 1)
        names.append(data[p:p+count].decode('utf-16-le' if wide else 'latin-1'));p+=count
    export=u32(0x34)+u32(0x38);base=export+0x20;size=u32(export+0xc)
    image=bytearray(data[base:base+size])
    patches={};p=base+size+8;count=u32(p);p+=4
    for _ in range(count):
        name,number,n=struct.unpack_from('<iii',data,p);p+=12
        if not 0<=name<len(names) or number<0:raise ValueError('Invalid name patch')
        for _ in range(n):
            offset=u32(p);p+=4
            if not 0<=offset<=size-8 or offset in patches:raise ValueError('Invalid patch offset')
            patches[offset]=names[name] if number==0 else f'{names[name]}_{number-1}'
            image[offset:offset+8]=b'\0'*8
    def val(p):return struct.unpack_from('<I',image,p)[0]
    def ptr(p):
        value=struct.unpack_from('<q',image,p)[0]
        if value&1!=1:raise ValueError('Expected frozen relative pointer')
        target=p+(value>>1)
        if not 0<=target<size:raise ValueError('Pointer outside frozen image')
        return target
    keys=ptr(0);entries=ptr(0x48);properties=ptr(0x38)
    if (val(8),val(0x50),val(0x40))!=(44,44,38):raise ValueError('Unexpected table dimensions')
    indices={patches[keys+20*i]:val(keys+20*i+8) for i in range(44)}
    if sorted(indices.values())!=list(range(44)):raise ValueError('Unexpected row indices')
    sizes={1:1,2:1,3:1,4:2,6:4,7:4,8:8,9:4,10:16,11:8}
    fields={};offset=0;maximum=1
    align=lambda x,a:(x+a-1)//a*a
    for i in range(38):
        record=properties+12*i;name=patches[record];kind=val(record+8);array=name.endswith('_Array')
        alignment=8 if array or kind==10 else 4 if kind==11 else sizes[kind]
        offset=align(offset,alignment);fields[name]=offset
        offset+=16 if array else sizes[kind];maximum=max(maximum,alignment)
    stride=align(offset,maximum)
    targets=[]
    for name in ('Grassland_mob_05','Grassland_mob_23','Grassland_mob_29','Grassland_mob_30'):
        descriptor=entries+stride*indices[name]+fields['MobTemplateList_Array']
        if (val(descriptor+8),val(descriptor+12))!=(2,2):raise ValueError('Unexpected template list dimensions')
        target=ptr(descriptor)
        if patches[target]!='mobgrasa_KalmFang_00' or patches[target+8]!='mobgrasa_Ogre_Orc_00':
            raise ValueError('Unexpected target templates')
        targets.append({'id':name,'descriptor':descriptor,'offset':target})
    donor=entries+stride*indices['Grassland_mob_18']+fields['MobTemplateList_Array']
    mu=ptr(donor)
    if patches[mu]!='mobgrasa_Mu_00' or patches[mu+8]!='mobgrasa_Ogre_Orc_00':
        raise ValueError('Unexpected Mu donor templates')
    options=[targets[0]['offset'],mu]
    return {'bytes':size,'masked_sha256':hashlib.sha256(image).hexdigest(),
            'patches':[{'offset':k,'name':v} for k,v in sorted(patches.items())],
            'targets':targets,'options':options}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--asset',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args();manifest=layout(args.asset)
    quoted=lambda s:'L'+json.dumps(s,ensure_ascii=True)
    lines=['// Generated by tools/runtime_layout.py from the reviewed original hash.',
           '// Offsets/names/fingerprint only; no original asset payload.',
           '#pragma once','#include <cstdint>','namespace reviewed {',
           f'constexpr std::size_t image_bytes={manifest["bytes"]};',
           f'constexpr char masked_sha256[]={json.dumps(manifest["masked_sha256"])};',
           'struct NamePatch {std::uint32_t offset;const wchar_t* name;};',
           'constexpr NamePatch names[]={']
    lines += [f'    {{{p["offset"]},{quoted(p["name"])}}},' for p in manifest['patches']]
    lines += ['};','struct Target {const wchar_t* id;std::uint32_t descriptor;};','constexpr Target targets[]={']
    lines += [f'    {{{quoted(t["id"])},{t["descriptor"]}}},' for t in manifest['targets']]
    lines += ['};',f'constexpr std::uint32_t options[]={{{",".join(map(str,manifest["options"]))}}};','}']
    args.output.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(json.dumps({k:v for k,v in manifest.items() if k!='patches'}|{'name_patch_count':len(manifest['patches'])}))

if __name__=='__main__':main()
